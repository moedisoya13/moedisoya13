/* The square of canvas a catalogue's bout stands on (the motion catalogue, the effect study, the review sheet with fx=1):
   tiles, so that where a foot lands can be seen, in the canvas's own ramp (22 to 24, the seams darkest). Flat at the
   canvas's height, with no bones: a ring through the canvas (renderer.mjs: a layer's ground) lifts them where they are.
     floor(half, centre) -> { rows, count }: a splat every 8.5 cm over the square `half` metres either side of centre [x, z] */
export function floor(half, centre) {
  const gap = 0.085,
    n = Math.round((half * 2) / gap),
    rows = new Float32Array(n * n * 12),
    s = 0.042 ** 2;
  let k = 0;
  for (let i = 0; i < n; i++)
    for (let j = 0; j < n; j++) {
      const x = centre[0] - half + (i + 0.5) * gap,
        z = centre[1] - half + (j + 0.5) * gap,
        tile = 0.5,
        fx = Math.abs((((x / tile) % 1) + 1.5) % 1 - 0.5) * tile,
        fz = Math.abs((((z / tile) % 1) + 1.5) % 1 - 0.5) * tile,
        dark = (Math.floor(x / tile + 100) + Math.floor(z / tile + 100)) % 2;
      rows.set([x, 0, z, s, 0, 0, 1e-6, 0, s, fx < 0.03 || fz < 0.03 ? 22 : dark ? 23 : 24, 0, 3], k);
      k += 12;
    }
  return { rows, count: n * n };
}
